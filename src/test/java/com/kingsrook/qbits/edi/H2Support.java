/*******************************************************************************
 ** Isolated H2 databases with DDL derived from the actual QQQ metadata.
 *******************************************************************************/
public final class H2Support
{
   /*******************************************************************************
    ** Install and validate a real RDBMS instance and generate its tables.
    *******************************************************************************/
   public static QInstance create() throws Exception
   {
      String name = "edi_" + UUID.randomUUID().toString().replace("-", "");
      RDBMSBackendMetaData backend = new RDBMSBackendMetaData().withName(name).withVendor("h2").withUsername("sa").withPassword("")
         .withJdbcUrl("jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1;DATABASE_TO_UPPER=FALSE");
      QInstance instance = new QInstance().withInstanceDefaultAuthentication(new QAuthenticationMetaData().withName("anonymous").withType(QAuthenticationType.FULLY_ANONYMOUS));
      instance.addBackend(backend);
      new EdiQBitProducer().withQBitConfig(new EdiQBitConfig().withBackendName(name).withPartnerLocks(true)
         .withSecretsResolver(key -> Base64.getEncoder().encodeToString(new byte[32]))).produce(instance);
      new QInstanceValidator().validate(instance);
      try(Connection connection = ConnectionManager.getConnection(backend); Statement statement = connection.createStatement())
      {
         for(QTableMetaData table : instance.getTables().values())
         {
            if(!table.getName().equals("edi_preview_download"))
            {
               statement.execute(ddl(table, false));
            }
         }
      }
      QContext.init(instance, new QSystemUserSession(instance));
      return (instance);
   }

   /*******************************************************************************
    ** Shared schema generator used for H2 execution and committed PostgreSQL DDL verification.
    *******************************************************************************/
   public static String ddl(QTableMetaData table, boolean postgres)
   {
      List<String> columns = new ArrayList<>();
      for(QFieldMetaData field : table.getFields().values().stream().sorted(java.util.Comparator.comparing(QFieldMetaData::getName)).toList())
      {
         String type = switch(field.getType())
         {
            case INTEGER -> "INTEGER";
            case LONG -> "BIGINT";
            case BOOLEAN -> "BOOLEAN";
            case DATE_TIME -> "TIMESTAMP";
            case DATE -> "DATE";
            case DECIMAL -> "DECIMAL(30,10)";
            case BLOB -> postgres ? "BYTEA" : "BLOB";
            default -> "VARCHAR(" + (field.getMaxLength() == null ? 10000 : field.getMaxLength()) + ")";
         };
         columns.add(field.getBackendName() + " " + type + (field.getName().equals("id") ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : ""));
      }
      for(UniqueKey key : table.getUniqueKeys() == null ? List.<UniqueKey>of() : table.getUniqueKeys())
      {
         columns.add("UNIQUE (" + key.getFieldNames().stream().map(f -> table.getField(f).getBackendName()).collect(Collectors.joining(", ")) + ")");
      }
      return ("CREATE TABLE " + table.getName() + " (\n   " + String.join(",\n   ", columns) + "\n)");
   }
}
